#!/usr/bin/env python3
"""namemap.py - rebuilds docs/NAME_MAP.md from the source comments.

Every ported class and member names the obfuscated identifier it comes from
in a comment ("original: _SafePkg_805/_SafeStr_972", "///< _SafeStr_1145").
This script collects them, file by file, into one table.

    python3 tools/namemap.py > docs/NAME_MAP.md
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OBFUSCATED = re.compile(r"(_Safe(?:Str|Cls|Pkg)_\d+(?:/_Safe(?:Str|Cls)_\d+|/\w+)?|[A-Za-z_]\w*\._SafeStr_\d+)")
HEADER_ORIGINAL = re.compile(r"\(original:\s*([^)]*)\)", re.IGNORECASE | re.DOTALL)


def member_name(code):
    """The name declared by a line of C++ (function, field or constant)."""
    code = code.split("//")[0]
    match = re.search(r"([A-Za-z_~][\w:]*)\s*\(", code)  # a function
    if match and not code.lstrip().startswith(("return", "if")):
        return match.group(1) + "()"
    match = re.search(r"([A-Za-z_]\w*)\s*(?:=[^=].*)?[;{]", code)  # a variable
    return match.group(1) if match else None


def entries(path):
    text = path.read_text()
    header = text.split("#pragma once")[0] if "#pragma once" in text else ""
    classes = [m.group(1).strip() for m in HEADER_ORIGINAL.finditer(header)]
    rows = []
    pending = []  # comment lines naming an original, before the declaration they document
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("///") and not stripped.startswith("///<"):
            pending += OBFUSCATED.findall(stripped)
            continue
        names = OBFUSCATED.findall(line.split("///<")[1]) if "///<" in line else []
        names = names or pending
        pending = []
        if not names or stripped.startswith(("//", "#")):
            continue
        name = member_name(line)
        if name:
            rows.append((name, ", ".join(dict.fromkeys(names))))
    return classes, rows


def main():
    print("# Name map: obfuscated identifier -> port name\n")
    print("The decompiler shows the obfuscated identifiers of the original as")
    print("`_SafePkg_N` (packages), `_SafeCls_N` (classes) and `_SafeStr_N` (members);")
    print("the SWF itself holds `_-XY` strings. The port gives everything a real name")
    print("and records the original one next to the declaration, in a comment.")
    print("This file collects those comments (generated by `tools/namemap.py`).\n")
    print("Names that were not obfuscated (`Level`, `GamePanel`, `update`...) are kept")
    print("as they are and not listed. To find the port of an obfuscated name, search")
    print("this file; to see the evidence, open the ported file and the decompiled one.\n")
    for folder in ("engine", "game"):
        for path in sorted((ROOT / folder).rglob("*.h")):
            classes, rows = entries(path)
            if not classes and not rows:
                continue
            rel = path.relative_to(ROOT)
            print(f"## `{rel}`\n")
            if classes:
                print("Original: " + "; ".join(c.replace("\n", " ").replace("//", "").strip() for c in classes) + "\n")
            if rows:
                print("| Port | Original |")
                print("|---|---|")
                for name, original in rows:
                    print(f"| `{name}` | `{original}` |")
                print()


if __name__ == "__main__":
    main()
